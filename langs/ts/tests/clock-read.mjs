import assert from 'node:assert/strict';
import vm from 'node:vm';
import { Environment } from '../exec/fake.mjs';
import { sandbox } from '../exec/run.mjs';

const sample = (seed, source) => {
  const env = new Environment(seed);
  const { ctx } = sandbox(env);
  return { value: vm.runInContext(source, ctx), trace: env.trace };
};
const source = `(() => {
  const first = Date.now();
  const second = new Date().getTime();
  const high = performance.now();
  const start = process.hrtime();
  const elapsed = process.hrtime(start);
  const nano = process.hrtime.bigint();
  return [first, second, high, Array.isArray(start), elapsed[0], elapsed[1], typeof nano];
})()`;
const a = sample(7, source), b = sample(7, source), c = sample(8, source);
assert.equal(JSON.stringify(a), JSON.stringify(b));
assert.notEqual(a.value[0], c.value[0]);
assert(a.value[1] > a.value[0]);
assert.equal(typeof a.value[2], 'number');
assert.notEqual(a.value[2], Math.floor(a.value[2]));
assert.equal(a.value[3], true);
assert(a.value[4] >= 0 && a.value[5] >= 0 && a.value[5] < 1000000000);
assert.equal(a.value[6], 'bigint');
assert.deepEqual(a.trace.map((x) => x.path), ['Date.now', 'Date', 'performance.now', 'process.hrtime', 'process.hrtime', 'process.hrtime.bigint']);
assert.equal(a.trace[4].args.length, 1);
const fixed = sample(7, '[new Date(0).getTime(), Date.parse("2000-01-01T00:00:00Z"), Date.UTC(2000, 0, 1)]');
assert.deepEqual(Array.from(fixed.value), [0, 946684800000, 946684800000]);
assert.deepEqual(fixed.trace, []);
const subclass = sample(7, 'class Moment extends Date {}; const d = new Moment(); [d instanceof Moment, d instanceof Date, d.getTime()]');
assert.equal(subclass.value[0], true);
assert.equal(subclass.value[1], true);
assert.equal(subclass.trace.length, 1);
const identity = sample(7, 'Date.now === Date.now && performance.now === performance.now && process.hrtime === process.hrtime');
assert.equal(identity.value, true);
assert.deepEqual(identity.trace, []);
const ignored = sample(7, 'Date("ignored")');
assert.equal(typeof ignored.value, 'string');
assert.equal(ignored.trace.length, 1);
console.log('clock fakes: seeded replay, advancing reads, typed results, arguments, fixed values and subclassing PASS');
