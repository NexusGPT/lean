"""lean-py test run: the pairs (both lanes) and the escapes.

    python3 -I langs/py/tests/run.py [pair ...] [--no-b] [--escapes]

Pairs: langs/py/tests/pairs/<name>/{parent.py, candidate.py, expect.json} (+ sibling modules). Both sides are
translated with --core --suffix and a prelude (the world classification agreed between the two sides, as the
TypeScript suite does), the theorem is generated by spec/theorem.py with every unit of `scope` outside S, and Dafny
verifies it. A lemma counts as proved only when it has no error AND the translation itself has none (an error
outside every lemma is a defect of the translation, never a proof). Lane B runs per unit of `b`.
Escapes: every file under fixtures/escapes/py/ and langs/py/tests/escapes/ names its rule on its first line
(`# expect: <rule>`); the lint must exit 1 naming it with its rewrite (`--json`: `label` and `advice`), and the
translator must refuse too. Every rule name in the lint's and the translator's sources has a rewrite in lint/advice.py.
`--escapes` runs only these (no Dafny).
Prints a table; the last line is `| TOTAL | N checks | ALL PASS |` or `| TOTAL | N checks | K FAILED |`.
"""
import json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PY = os.path.dirname(HERE)
sys.path.insert(0, PY)
from common import Module, dafny_name  # noqa: E402
ROOT = os.path.dirname(os.path.dirname(PY))
LINT = os.path.join(PY, 'lint', 'lint.py')
TRANSLATE = os.path.join(PY, 'translate', 'translate.py')
RUN_B = os.path.join(PY, 'exec', 'run.py')
THEOREM = os.path.join(ROOT, 'spec', 'theorem.py')
ROWS = []


def add(kind, name, check, ok, detail=''):
    ROWS.append((kind, name, check, ok, detail))


def run(argv, timeout=900):
    r = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True, timeout=timeout)
    return r.returncode, r.stdout + r.stderr


def header(path, key):
    m = re.search(r'^// ' + key + r': (.*)$', open(path).read(), re.M)
    return m.group(1).strip() if m else ''


def pair(name, tmp, lane_b=True):
    d = os.path.join(HERE, 'pairs', name)
    exp = json.load(open(os.path.join(d, 'expect.json')))
    t = os.path.join(tmp, name)
    os.makedirs(t, exist_ok=True)

    def tr(which, eff):
        return run([sys.executable, '-I', TRANSLATE, os.path.join(d, which + '.py'), '--core', '--suffix', which,
                    '--out', os.path.join(t, which + '.dfy'), '--prelude', os.path.join(t, which + '.pre.dfy')]
                   + (['--effectful', eff] if eff else []))
    rc, out = tr('parent', '')
    if rc != 0:
        add('pair', name, 'translate parent', False, out.strip()[-200:])
        return
    eff = header(os.path.join(t, 'parent.dfy'), 'EFFECTFUL')
    rc, out = tr('candidate', eff)
    if rc != 0:
        add('pair', name, 'translate candidate', False, out.strip()[-200:])
        return
    eff2 = header(os.path.join(t, 'candidate.dfy'), 'EFFECTFUL')
    if eff2 != eff:
        tr('parent', eff2)
    scope = os.path.join(t, 'scope.json')
    json.dump({'functions': {f: {'in_scope': 'false'} for f in exp['scope']}}, open(scope, 'w'))
    edit = os.path.join(t, 'edit.json')
    open(edit, 'w').write('{}')
    thm = os.path.join(t, 'theorem.dfy')
    rc, out = run([sys.executable, '-I', THEOREM, '--parent', os.path.join(t, 'parent.dfy'), '--candidate',
                   os.path.join(t, 'candidate.dfy'), '--scope', scope, '--edit', edit, '--out', thm])
    add('pair', name, 'theorem generated', rc == 0, 'ok' if rc == 0 else out.strip()[-200:])
    if rc != 0:
        return
    rc, text = run(['dafny', 'verify', '--verification-time-limit', '30', thm])
    lines = open(thm).read().split('\n')
    spans, cur = {}, None
    for i, ln in enumerate(lines, 1):
        m = re.match(r'^lemma (?:\{[^}]*\}\s+)*(Equal_\w+)(?:<[^>]*>)?\(', ln)
        if m:
            cur = m.group(1)
            spans[cur] = [i, None]
        if re.match(r'^\} // END Equal_', ln) and cur:
            spans[cur][1] = i
    errs = [int(m.group(1)) for m in re.finditer(r'theorem\.dfy\((\d+),\d+\): Error', text)]
    finished = re.search(r'finished with \d+ verified', text) is not None
    outside = [L for L in errs if not any(s[0] <= L <= s[1] for s in spans.values())]
    clean = finished and not outside
    add('pair', name, 'translation verifies', clean, 'no error outside the lemmas' if clean else
        ('errors outside the lemmas at lines ' + ', '.join(map(str, outside[:6])) if finished else text.strip().split('\n')[-1][:200]))
    proved_units = []
    for f, want in exp['equal'].items():
        sp = spans.get(f'Equal_{f}')
        withheld = next((l for l in lines if l.startswith(f'// UNGUARDED Equal_{f}: ')), None)
        proved = clean and sp is not None and not any(sp[0] <= L <= sp[1] for L in errs)
        got = ('proved' if proved else 'not proved') if sp else (f'withheld: {withheld[:100]}' if withheld else 'lemma missing')
        ok = (proved == want) and sp is not None
        add('pair', name, f'Equal_{f} {"proved" if want else "not proved"}', ok, got)
        if proved:
            proved_units.append(f)
    if not lane_b:
        return
    verdicts = {}

    def lane_b(unit):
        out = os.path.join(t, f'b_{unit}.json')
        rc, txt = run([sys.executable, '-I', RUN_B, '--parent', os.path.join(d, 'parent.py'), '--candidate',
                       os.path.join(d, 'candidate.py'), '--unit', unit, '--n', '30', '--out', out])
        try:
            verdicts[unit] = json.load(open(out))['verdict']
        except (OSError, ValueError, KeyError):
            verdicts[unit] = 'no result: ' + txt.strip()[-160:]
        return verdicts[unit]
    for unit, want in exp.get('b', {}).items():
        got = lane_b(unit)
        add('pair', name, f'lane B {unit} {want}', got == want, got)
    # a proof the bounded run contradicts is a false proof: every proved unit runs through lane B too
    by_dafny = {dafny_name(u.name): u.name for u in Module(os.path.join(d, 'parent.py')).units()}
    for f in proved_units:
        unit = by_dafny.get(f)
        if unit is None:
            continue
        got = verdicts.get(unit) or lane_b(unit)
        add('pair', name, f'proved {f}: lane B agrees', got != 'WITNESS', got)


def escapes(tmp):
    dirs = [os.path.join(ROOT, 'fixtures', 'escapes', 'py'), os.path.join(HERE, 'escapes')]
    for d in dirs:
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith('.py'):
                continue
            p = os.path.join(d, f)
            first = open(p).readline()
            m = re.match(r'#\s*expect:\s*(\S+)', first)
            name = os.path.relpath(p, ROOT)
            if not m:
                add('escape', name, 'expect line', False, 'missing `# expect: <rule>`')
                continue
            want = m.group(1)
            rc, out = run([sys.executable, '-I', LINT, p])
            hit = any(re.search(r'\s' + re.escape(want) + r'\s', l) for l in out.split('\n'))
            add('escape', name, f'lint refuses: {want}', rc == 1 and hit,
                ('refused: ' + want) if rc == 1 and hit else (f'refused, but not for {want}: {out.strip()[:120]}' if rc == 1 else 'ACCEPTED'))
            # the finding names the construct and what to write instead, as the TypeScript lint's does
            rc3, out3 = run([sys.executable, '-I', LINT, p, '--json'])
            try:
                rows = [r for r in json.loads(out3)['findings'] if r['rule'] == want]
            except (ValueError, KeyError, TypeError):
                rows = []
            named = [r for r in rows if r.get('advice') and r.get('label') and 'unit' in r]
            add('escape', name, 'lint names the rewrite', bool(named),
                (named[0]['label'] + ': ' + named[0]['advice'][:80]) if named else ('no advice on the finding' if rows else 'no --json finding: ' + out3.strip()[:100]))
            rc2, out2 = run([sys.executable, '-I', TRANSLATE, p, '--core', '--out', os.path.join(tmp, 'esc.dfy')])
            add('escape', name, 'translate refuses', rc2 == 1, 'refused' if rc2 == 1 else 'TRANSLATED')


def rule_names():
    """Every rule name the lint and the translator can emit, read from their sources: the second argument of a
    `fail`, `Unsupported` or `v` call, and the first of a (rule, message) pair of string literals."""
    import ast
    names = {}
    for f in (LINT, TRANSLATE, os.path.join(PY, 'common.py')):
        for n in ast.walk(ast.parse(open(f).read())):
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id in ('fail', 'Unsupported', 'v') \
                    and len(n.args) >= 2 and isinstance(n.args[1], ast.Constant) and isinstance(n.args[1].value, str):
                names.setdefault(n.args[1].value, f'{os.path.basename(f)}:{n.lineno}')
            elif isinstance(n, ast.Tuple) and len(n.elts) == 2 and all(isinstance(e, ast.Constant) and isinstance(e.value, str) for e in n.elts) \
                    and re.fullmatch(r'[a-z]+(-[a-z]+)*', n.elts[0].value) and ' ' in n.elts[1].value:
                names.setdefault(n.elts[0].value, f'{os.path.basename(f)}:{n.lineno}')
    return names


def advice_coverage():
    sys.path.insert(0, os.path.join(PY, 'lint'))
    try:
        from advice import ADVICE
    except ImportError as e:
        add('lint', 'advice.py', 'every rule has a rewrite', False, f'no advice table: {e}')
        return
    missing = [f'{r} ({w})' for r, w in sorted(rule_names().items()) if r not in ADVICE]
    add('lint', 'advice.py', 'every rule has a rewrite', not missing, 'missing: ' + ', '.join(missing[:8]) if missing else f'{len(rule_names())} rules')


def main(argv):
    lane_b = '--no-b' not in argv
    if '--escapes' in argv:  # the lint only: the advice table and the escapes, no Dafny
        with tempfile.TemporaryDirectory(prefix='lean-py-') as tmp:
            advice_coverage()
            escapes(tmp)
        return table()
    names = [a for a in argv if not a.startswith('--')]
    allp = sorted(os.listdir(os.path.join(HERE, 'pairs')))
    with tempfile.TemporaryDirectory(prefix='lean-py-') as tmp:
        for name in names or allp:
            pair(name, tmp, lane_b)
        if not names:
            advice_coverage()
            escapes(tmp)
            rc, out = run([sys.executable, '-I', os.path.join(ROOT, 'conformance', 'run.py'), 'py'])
            add('repo', 'conformance/run.py py', 'runner', rc == 0, out.strip().split('\n')[-1])
    return table()


def table():
    w = [max(len(str(r[i])) for r in ROWS + [('kind', 'name', 'check')]) for i in range(3)]
    print(f'| {"kind":<{w[0]}} | {"name":<{w[1]}} | {"check":<{w[2]}} | res  | detail')
    for r in ROWS:
        print(f'| {r[0]:<{w[0]}} | {r[1]:<{w[1]}} | {r[2]:<{w[2]}} | {"PASS" if r[3] else "FAIL"} | {r[4]}')
    failed = sum(1 for r in ROWS if not r[3])
    print(f'| TOTAL | {len(ROWS)} checks | {"ALL PASS" if not failed else f"{failed} FAILED"} |')
    return 0 if not failed else 1


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
